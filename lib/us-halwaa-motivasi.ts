export type MotivasiCategory = keyof typeof MOTIVASI;

// Global memory for tracking last 3 motivations
const last3Motivasi: string[] = [];

export function getRandomMotivasi(category: MotivasiCategory): string {
  const list = MOTIVASI[category] || MOTIVASI.energi_positif;
  const available = list.filter((item) => !last3Motivasi.includes(item));
  const pool = available.length > 0 ? available : list;

  const randomIndex = Math.floor(Math.random() * pool.length);
  const selected = pool[randomIndex];

  last3Motivasi.push(selected);
  if (last3Motivasi.length > 3) {
    last3Motivasi.shift();
  }

  return selected;
}

export function detectMotivasiIntent(q: string): MotivasiCategory | null {
  const query = q.toLowerCase().trim();

  if (/saya siapa|siapa saya|aku siapa|aku ini siapa/.test(query)) {
    return 'identitas';
  }

  if (/capek|lelah|penat|ngantuk|pusing|letih|lesu/.test(query)) {
    return 'lelah';
  }

  if (/terima kasih|makasih|thanks|syukron|jazakallah/.test(query)) {
    return 'syukur';
  }

  if (/tugas.*(berat|sulit|rumit|banyak)|susah|sulit|rumit/.test(query)) {
    return 'tugas_berat';
  }

  if (/sudah selesai|alhamdulillah selesai|beres|kelar|tuntas/.test(query)) {
    return 'selesai';
  }

  if (/target|cita-cita|impian|harapan|mimpi/.test(query)) {
    return 'harapan';
  }

  if (/sedih|galau|down|menangis|stress|stres|putus asa/.test(query)) {
    return 'sedih';
  }

  if (/ragu|takut|cemas|panik|bingung|buntu/.test(query)) {
    return 'tertekan';
  }

  if (/dedikasi|pengorbanan|balik layar|nggak kelihatan/.test(query)) {
    return 'dedikasi';
  }

  if (/peran saya|kontribusi saya|nilai saya/.test(query)) {
    return 'nilai_diri';
  }

  return null;
}

