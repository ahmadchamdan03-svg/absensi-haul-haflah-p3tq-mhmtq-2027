/**
 * Mengambil 1 kalimat pujian secara acak dari 50 TEMPLATE_PUJIAN
 * dengan memori anti-pengulangan (10 pemanggilan terakhir tidak akan berulang).
 */
export function getRandomPujian(): string {
  const candidates = TEMPLATE_PUJIAN.map((_, i) => i).filter(
    (i) => !recentPujianIndices.includes(i)
  );
  const pool = candidates.length > 0 ? candidates : TEMPLATE_PUJIAN.map((_, i) => i);
  const chosenIdx = pool[Math.floor(Math.random() * pool.length)];

  recentPujianIndices.push(chosenIdx);
  if (recentPujianIndices.length > 10) {
    recentPujianIndices.shift();
  }
  return TEMPLATE_PUJIAN[chosenIdx];
}

